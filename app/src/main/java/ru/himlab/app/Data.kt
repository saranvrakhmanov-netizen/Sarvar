enum class OutcomeType(
    val label: String,
    val color: Color,
    val meaning: String,
) {
    MIX("Смешались", Color(0xFF1FB5A6), "вещества перемешались и растворились друг в друге"),
    LAYERS("Слои", Color(0xFF7C5CFF), "вещества не смешиваются и лежат слоями или оседают на дно"),
    REACTION("Реакция!", Color(0xFFFF8A3D), "из веществ получились новые вещества"),
    DRY("Просто рядом", Color(0xFF9AA3B8), "вещества лежат рядом, каждое осталось самим собой"),
}

